"""Dataset manifest and loaders for the benchmark harness.

Only redistributable data is generated by default. Real market data comes from the user's own
licensed files (``--data-dir``), is read through the point-in-time file provider, and is never
copied anywhere by this harness.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import pandas as pd
import yaml

from tycheon.data.providers.file import FileProvider
from tycheon.data.sample import SAMPLE_DATASETS, make_synthetic_bars

MANIFEST_PATH = Path(__file__).resolve().parent / "datasets" / "manifest.yaml"


class DatasetError(ValueError):
    """A dataset that is unknown, unavailable or not allowed for this run."""


@dataclass(frozen=True)
class Dataset:
    name: str
    entry: dict[str, Any]

    @property
    def synthetic(self) -> bool:
        return bool(self.entry.get("synthetic", False))

    @property
    def redistributable(self) -> bool:
        return bool(self.entry.get("redistributable", False))


def load_manifest(path: Path = MANIFEST_PATH) -> dict[str, Any]:
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict) or "datasets" not in raw:
        raise DatasetError(f"{path}: not a dataset manifest")
    return dict(raw)


def manifest_sha256(path: Path = MANIFEST_PATH) -> str:
    # normalise line endings so the hash is the same on every platform
    text = path.read_bytes().replace(b"\r\n", b"\n")
    return hashlib.sha256(text).hexdigest()


def get_dataset(name: str, path: Path = MANIFEST_PATH) -> Dataset:
    datasets = load_manifest(path)["datasets"]
    if name not in datasets:
        raise DatasetError(f"unknown dataset {name!r}; the manifest lists {sorted(datasets)}")
    return Dataset(name, dict(datasets[name]))


def load_series(dataset: Dataset, symbol: str, data_dir: Path | None) -> pd.DataFrame:
    """One symbol's bars, all of them, with ``available_at``.

    Synthetic data is generated from its fixed seed. Licensed data is read from ``data_dir``
    and the harness refuses to run a ``user-license`` dataset without one.
    """
    kind = dataset.entry.get("kind")
    if kind == "synthetic":
        if symbol not in SAMPLE_DATASETS:
            raise DatasetError(f"{symbol!r} is not a bundled synthetic series")
        return make_synthetic_bars(SAMPLE_DATASETS[symbol])
    if kind == "user-license":
        if data_dir is None:
            raise DatasetError(
                f"dataset {dataset.name!r} is your own licensed data: pass --data-dir. "
                f"{dataset.entry.get('how_to_fetch', '')}".strip()
            )
        provider = FileProvider(data_dir, fmt=dataset.entry.get("format", "csv"))
        far_future = pd.Timestamp("2100-01-01", tz="UTC")
        return provider.fetch_bars(
            symbol, start=None, end=None, as_of=far_future, frequency=dataset.entry["frequency"]
        )
    raise DatasetError(f"dataset {dataset.name!r} has unsupported kind {kind!r}")
